"""End-to-end bounded rank-basis HyperSpline feasibility experiment.

Train on teacher-cache bags from explicitly named datasets and evaluate on
whole held-out datasets.  The fixed rank-R curve basis is fitted only from the
training datasets; query cross entropy through frozen TabICL is the only
learning signal.  Individual DirectSpline teachers are never imitation labels.
"""

